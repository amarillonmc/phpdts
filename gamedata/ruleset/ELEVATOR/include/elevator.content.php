function elevator_item($id,$round='') {
    $c=elevator_catalog(); $s=$c[$id];
    return array('itm'=>$s['name'],'itmk'=>$s['kind'],'itme'=>$s['effect'],'itms'=>$s['quantity'],
        'itmsk'=>'','itmpara'=>array('elevator_item'=>(int)$id,'elevator_round'=>$round));
}
function elevator_item_id($name) {
    foreach (elevator_catalog() as $id=>$item) if ($item['name']===$name) return $id;
    return 0;
}
